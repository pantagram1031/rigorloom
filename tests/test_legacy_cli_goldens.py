# -*- coding: utf-8 -*-
"""Legacy CLI golden regression suite.

Freezes argv grammar, exit codes, stderr emptiness, and normalised non-TTY
stdout for existing ``rigorloom`` CLI commands before adding new top-level
product verbs.

All golden files live under ``tests/legacy_cli/goldens/*.json`` and are
generated by ``tests/legacy_cli/capture.py``.
"""
from __future__ import annotations

import difflib
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest

TESTS_DIR = Path(__file__).resolve().parent
REPO_ROOT = TESTS_DIR.parent
CLI_SCRIPT = REPO_ROOT / "runtime" / "scripts" / "cli.py"
CAPTURE_SCRIPT = TESTS_DIR / "legacy_cli" / "capture.py"
GOLDENS_DIR = TESTS_DIR / "legacy_cli" / "goldens"

#: Generous bound compatible with tests/test_subprocess_bounds.py (> 20s).
RUN_TIMEOUT = 120

GOLDEN_FILES = sorted(GOLDENS_DIR.glob("*.json")) if GOLDENS_DIR.is_dir() else []
if not GOLDEN_FILES:
    pytest.skip(
        f"legacy CLI golden fixtures are missing under {GOLDENS_DIR}; "
        "run `python tests/legacy_cli/capture.py` to generate them",
        allow_module_level=True,
    )

if str(TESTS_DIR) not in sys.path:
    sys.path.insert(0, str(TESTS_DIR))

from test_cli_distribution import (  # noqa: E402,F401
    build_python,
    built_wheel,
    installed_cli,
)


def _load_capture_module():
    spec = importlib.util.spec_from_file_location("legacy_cli_capture", CAPTURE_SCRIPT)
    assert spec is not None and spec.loader is not None, (
        f"could not load {CAPTURE_SCRIPT}"
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


capture = _load_capture_module()


def _load_goldens() -> dict[str, dict]:
    loaded: dict[str, dict] = {}
    for path in GOLDEN_FILES:
        loaded[path.stem] = json.loads(path.read_text(encoding="utf-8"))
    return loaded


GOLDENS = _load_goldens()


def _assert_matches_golden(name: str, actual: dict, golden: dict) -> None:
    assert actual["argv"] == golden["argv"], (
        f"{name}: argv template drifted: {actual['argv']!r} != {golden['argv']!r}"
    )
    assert actual["exit"] == golden["exit"], (
        f"{name}: exit code {actual['exit']} != expected {golden['exit']}\n"
        f"actual stdout:\n{actual['stdout_normalized']}"
    )
    assert actual["stderr_is_empty"] == golden["stderr_is_empty"], (
        f"{name}: stderr_is_empty={actual['stderr_is_empty']} != "
        f"expected {golden['stderr_is_empty']}"
    )
    expected_out = capture.normalize_for_compare(golden["stdout_normalized"])
    actual_out = capture.normalize_for_compare(actual["stdout_normalized"])
    if name.startswith("help_") and expected_out.split() == actual_out.split():
        # argparse wraps long usage lines differently across Python versions
        # (3.13 keeps "..." on the choices line); the words are the contract.
        return
    if actual_out != expected_out:
        diff = "\n".join(
            difflib.unified_diff(
                expected_out.splitlines(keepends=False),
                actual_out.splitlines(keepends=False),
                fromfile=f"golden/{name}.json",
                tofile=f"actual/{name}",
                lineterm="",
            )
        )
        pytest.fail(f"{name}: normalised stdout drifted from golden:\n{diff}")


@pytest.fixture(scope="module")
def checkout_results() -> dict[str, dict]:
    assert set(GOLDENS) == set(capture.CASE_ORDER), (
        "golden inventory on disk does not match capture.CASE_ORDER: "
        f"missing={sorted(set(capture.CASE_ORDER) - set(GOLDENS))}, "
        f"extra={sorted(set(GOLDENS) - set(capture.CASE_ORDER))}"
    )
    case_argvs = [(name, GOLDENS[name]["argv"]) for name in capture.CASE_ORDER]
    return capture.run_case_sequence([sys.executable, str(CLI_SCRIPT)], case_argvs)


@pytest.mark.parametrize("case_name", capture.CASE_ORDER)
def test_legacy_cli_matches_golden(case_name: str, checkout_results: dict[str, dict]):
    """Re-run every legacy CLI case from the checkout and diff against golden."""
    _assert_matches_golden(case_name, checkout_results[case_name], GOLDENS[case_name])


def test_installed_cli_matches_goldens(installed_cli: Path):
    """Run every golden case through the installed ``rigorloom`` entry point.

    Reuses ``installed_cli`` from ``tests/test_cli_distribution.py`` and skips
    with its reason when no offline wheel toolchain is available. Protocol
    commands pass ``--engine-root <REPO_ROOT>`` because the wheel deliberately
    excludes ``engine/`` and ``pipeline/``.
    """
    assert set(GOLDENS) == set(capture.CASE_ORDER)
    case_argvs = [(name, GOLDENS[name]["argv"]) for name in capture.CASE_ORDER]
    actuals = capture.run_case_sequence(
        [str(installed_cli)],
        case_argvs,
        engine_root=REPO_ROOT,
    )
    for case_name in capture.CASE_ORDER:
        _assert_matches_golden(case_name, actuals[case_name], GOLDENS[case_name])


def test_doctor_no_engine_root_contract():
    """Structural contract for ``doctor`` (omitted from byte-for-byte goldens).

    ``doctor`` prints host-specific Python versions, executable paths, and
    ``setuptools``/``wheel`` probe results, so only its invariant envelope and
    unconfigured-engine verdict are pinned here.
    """
    proc = subprocess.run(
        [sys.executable, str(CLI_SCRIPT), "doctor"],
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=capture.build_env(),
        cwd=str(REPO_ROOT),
        timeout=RUN_TIMEOUT,
        check=False,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert proc.stderr == ""
    payload = json.loads(proc.stdout)
    assert payload["ok"] is True
    assert payload["command"] == "doctor"
    result = payload["result"]
    assert result["schema"] == "rigorloom-doctor/v1"
    assert result["requiredPassed"] is True
    by_id = {row["id"]: row for row in result["checks"]}
    assert list(by_id) == [
        "runtime_python",
        "child_python",
        "wheel_builder",
        "engine",
    ]
    assert by_id["runtime_python"]["state"] == "pass"
    assert by_id["child_python"]["state"] == "pass"
    assert by_id["engine"] == {
        "id": "engine",
        "required": False,
        "state": "unavailable",
        "reason": {
            "code": "engine_root_not_configured",
            "message": "No --engine-root was configured; installed-engine checks were not run.",
        },
    }


def test_capabilities_contract(tmp_path: Path):
    """Structural contract for ``capabilities`` (omitted from byte-for-byte goldens).

    ``capabilities`` embeds host interpreter path, checkout paths, CI-mutated
    ``modules/enabled.yaml`` state, OS-specific COM availability, and optional
    ``PIL``/``pymupdf`` availability, so invariant protocol fields are pinned here.
    """
    root = tmp_path / "root"
    proc = subprocess.run(
        [sys.executable, str(CLI_SCRIPT), "--root", str(root), "capabilities"],
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=capture.build_env(),
        cwd=str(REPO_ROOT),
        timeout=RUN_TIMEOUT,
        check=False,
    )
    assert proc.returncode == 0, proc.stdout + proc.stderr
    assert proc.stderr == ""
    payload = json.loads(proc.stdout)
    assert payload["ok"] is True
    assert payload["command"] == "capabilities"
    res = payload["result"]
    assert res["protocolVersion"] == "0"
    assert res["implVersion"] == "0.1.0"
    assert res["supportedBackends"] == ["preedit"]
    assert res["knownBackends"] == ["preedit", "xml", "com"]
    assert res["hwpEngine"] == {
        "available": False,
        "env": "RIGORLOOM_HWP_ENGINE",
        "reason": "engine_not_configured",
    }
    assert res["backends"]["preedit"]["state"] == "available"
    assert res["backends"]["xml"]["state"] == "unavailable"
    assert res["backends"]["com"]["state"] == "unavailable"
    assert set(res["tools"]) == {"check_residue", "form_inspect", "preedit"}
    for tool_info in res["tools"].values():
        assert tool_info["state"] == "available"
    assert res["methods"] == [
        "approval/get",
        "approval/request",
        "approval/resolve",
        "candidate/compare",
        "candidate/list",
        "capabilities/list",
        "document/inspect",
        "document/pageGeometry",
        "document/readRegion",
        "document/render",
        "document/renderPrepare",
        "event/poll",
        "event/subscribe",
        "event/unsubscribe",
        "initialize",
        "module/check",
        "module/list",
        "plan/apply",
        "plan/get",
        "plan/propose",
        "plan/validate",
        "receipt/read",
        "session/list",
        "workspace/openPath",
    ]
